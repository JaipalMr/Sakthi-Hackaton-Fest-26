"""DEMO MODE assistant: a deterministic, rule-based router that calls the SAME backend tools and fills a template.
It is NOT an LLM and every response is labelled as demo output."""
from __future__ import annotations

import re

from backend.app.schemas import AssistantContext
from ml import network as net

PREFIX = "[DEMO MODE - rule-based summary, not generated by an LLM] "


ALIASES = {"S01": ["main gate"], "S02": ["north gate"], "S03": ["riverside", "park & ride", "park and ride"],
           "S04": ["railway", "station"], "S05": ["bus terminal"], "S06": ["stadium"], "S07": ["old town", "market"],
           "S08": ["university", "campus"], "S09": ["lakeside"], "S10": ["airport"]}


def _stop_mentions(msg: str) -> list[str]:
    low = msg.lower()
    ids = {m.upper() for m in re.findall(r"\bs\d{2}\b", low)}
    for sid, words in ALIASES.items():
        if any(w in low for w in words):
            ids.add(sid)
    return sorted(i for i in ids if i in net.STOP_IDS)


def plan_tools(msg: str, ctx: AssistantContext) -> list[tuple[str, dict]]:
    low = msg.lower()
    calls: list[tuple[str, dict]] = []
    if re.search(r"what.?if|simulat|scenario|suppose|if it rain|rains?\b|closure|close[sd]?\b|later|earlier|fewer buses|less buses|cancel", low):
        args: dict = {}
        m = re.search(r"(\d+(?:\.\d+)?)\s*mm", low)
        if m:
            args["rainfall_mm_per_hr"] = min(float(m.group(1)), 30)
        elif "heavy rain" in low or "rain" in low:
            args["rainfall_mm_per_hr"] = 10.0
        m = re.search(r"(\d+)\s*(?:min|minutes)\s*(later|earlier)", low) or re.search(r"(later|earlier)\s*by\s*(\d+)", low)
        if m:
            g = m.groups()
            n, word = (int(g[0]), g[1]) if g[0].isdigit() else (int(g[1]), g[0])
            args["festival_end_shift_min"] = max(-60, min(60, n if word == "later" else -n))
        m = re.search(r"(\d+)\s*%\s*(?:fewer|less|of)?", low)
        if m and re.search(r"bus", low):
            pct = int(m.group(1))
            args["bus_availability_factor"] = round((100 - pct) / 100, 2) if re.search(r"fewer|less|cut|reduc|cancel", low) else round(pct / 100, 2)
        if re.search(r"clos", low):
            ids = _stop_mentions(msg)
            if ids:
                args["closed_stop_ids"] = ids
        if not args and ctx.scenario is None:
            return []
        if not args and ctx.scenario:
            sc = ctx.scenario
            args = dict(festival_end_shift_min=sc.festival_end_shift_min, rainfall_mm_per_hr=sc.rainfall_mm_per_hr,
                        bus_availability_factor=sc.bus_availability_factor, closed_stop_ids=sc.closed_stop_ids)
        calls.append(("run_what_if_simulation", args))
    elif re.search(r"recommend|deploy|move|reallocat|allocat|dispatch|where should|which buses|shift buses", low):
        calls.append(("get_deployment_recommendations", {}))
    elif _stop_mentions(msg) and re.search(r"stop|data|info|capacity|bus", low) and not re.search(r"risk|crowd|demand|forecast", low):
        calls.append(("get_stop_data", {"stop_ids": _stop_mentions(msg)}))
    else:
        args = {"stop_ids": _stop_mentions(msg)} if _stop_mentions(msg) else {}
        calls.append(("get_demand_forecast", args))
    return calls


def compose(calls: list[tuple[str, dict]], results: dict[str, dict], ctx: AssistantContext) -> str:
    if not calls:
        return (PREFIX + "I can forecast stop demand, recommend bus moves, or run what-if scenarios. "
                "Try: 'Which stops are at high risk?', 'Where should buses move?', or 'What if it rains 12 mm/h and the festival ends 30 minutes later?'. "
                "Every number I report comes from the backend model and optimiser.")
    name = calls[0][0]
    r = results[name]
    if name == "get_demand_forecast":
        stops = sorted(r["stops"], key=lambda s: (-["low", "elevated", "high"].index(s["peak_risk"]), -s["peak_step_demand"]))
        top = stops[:3]
        lines = [f"{s['name']} ({s['stop_id']}): peak {s['peak_step_demand']:.0f} passengers (80% interval {s['peak_step_interval'][0]:.0f}-{s['peak_step_interval'][1]:.0f}) "
                 f"vs service capacity {s['peak_step_service']:.0f}; risk {s['peak_risk']}" for s in top]
        tail = ""
        if r["festival_split_role"] in ("train", "validation"):
            tail = " Note: this festival was part of the model's training/validation data, so the fit looks better than it would on new events."
        return (PREFIX + f"Highest-risk stops over the next {r['steps_returned']} slots: " + "; ".join(lines) +
                f". Model test MAE is {r['model_test_mae']} passengers per stop-slot on synthetic data." + tail)
    if name == "get_deployment_recommendations":
        s = r["summary"]
        if not r["recommendations"]:
            return PREFIX + f"The optimiser found no feasible bus moves for {r['target_time']} (lead time {r['lead_time_min']:.0f} min). Unserved demand stays at {s['unserved_after']:.0f}."
        moves = "; ".join(f"{m['buses']} bus(es) {m['from_stop']} -> {m['to_stop']} ({m['travel_min']:.0f} min)" for m in r["recommendations"][:4])
        return (PREFIX + f"For {r['target_time']} the optimiser suggests: {moves}. Estimated unserved demand drops from {s['unserved_before']:.0f} to "
                f"{s['unserved_after']:.0f} passengers. These are advisory and need human approval before dispatch.")
    if name == "run_what_if_simulation":
        h = r["headline"]
        return (PREFIX + f"Scenario {r['scenario']} (hypothetical): total predicted demand at the target slot moves from {h['baseline_total_demand']:.0f} to "
                f"{h['scenario_total_demand']:.0f}; high-risk stops {h['baseline_high_risk_stops']:.0f} -> {h['scenario_high_risk_stops']:.0f}; unserved after reallocation "
                f"{h['baseline_unserved_after_reallocation']:.0f} -> {h['scenario_unserved_after_reallocation']:.0f}. "
                + ("Warnings: " + " ".join(r["warnings"]) + " " if r["warnings"] else "") + "This is a simulation under stated assumptions, not a verified outcome.")
    if name == "get_stop_data":
        return PREFIX + "; ".join(f"{s['name']}: {s['buses_planned']} buses planned, service capacity {s['service_capacity']:.0f}, waiting capacity {s['waiting_capacity']}"
                                  + (", route closed" if s["route_closed"] else "") for s in r["stops"])
    return PREFIX + "No summary available."
