"""LLM-written operations briefing. Facts are computed by the backend (forecast + optimiser); the LLM only turns them
into a short readable narrative. Falls back to a deterministic template (clearly labelled) if no LLM is available."""
from __future__ import annotations

import logging

from backend.app.assistant.llm_provider import LLMProvider, build_provider
from backend.app.assistant.service import DISCLAIMER, ungrounded_numbers
from backend.app.assistant.tools import run_tool, to_json
from backend.app.pipeline import Services
from backend.app.schemas import BriefingMove, BriefingRequest, BriefingResponse, BriefingRisk

log = logging.getLogger("briefing")
DEMO_PREFIX = "[DEMO MODE - template summary, not generated by an LLM] "
SYSTEM = """You write a short shift briefing for a festival transport control-room supervisor.
STRICT RULES:
- Use ONLY the numbers and stop names in the FACTS block. Never invent figures, stops or bus moves.
- 3 to 5 sentences, plain text, no markdown, no bullet points, under 120 words.
- Lead with the single most urgent issue, then the recommended bus moves (say they are advisory and need dispatcher approval),
  then one sentence of uncertainty/caveat (the data is synthetic).
- If there are no high-risk stops, say the situation looks stable."""
RISK_RANK = {"low": 0, "elevated": 1, "high": 2}


def _facts(svc: Services, req: BriefingRequest):
    ctx = req.context
    fc = run_tool(svc, "get_demand_forecast", {}, ctx)
    rec = run_tool(svc, "get_deployment_recommendations", {}, ctx)
    stops = sorted(fc["stops"], key=lambda s: (-RISK_RANK[s["peak_risk"]], -s["peak_step_demand"]))
    time_of = {t["step"]: t["time"] for t in fc["totals"]}
    risks = [BriefingRisk(stop_id=s["stop_id"], stop_name=s["name"], risk=s["peak_risk"], peak_demand=s["peak_step_demand"],
                          service_capacity=s["peak_step_service"], peak_time=time_of.get(s["peak_step"], "")) for s in stops[:4]]
    moves = [BriefingMove(from_stop=m["from_stop"], to_stop=m["to_stop"], buses=m["buses"], travel_min=m["travel_min"])
             for m in rec["recommendations"][:5]]
    return fc, rec, risks, moves


def _headline(risks: list[BriefingRisk]) -> str:
    high = [r for r in risks if r.risk == "high"]
    if high:
        return f"{len(high)} stop{'s' if len(high) > 1 else ''} at high crowd risk - {high[0].stop_name} is the priority"
    if any(r.risk == "elevated" for r in risks):
        return "Elevated load at some stops - monitor closely"
    return "Network looks stable for the forecast window"


def _template(risks, moves, rec) -> str:
    s = rec["summary"]
    parts = []
    if risks and risks[0].risk != "low":
        r = risks[0]
        parts.append(f"{r.stop_name} is the most pressured stop, peaking near {r.peak_demand:.0f} passengers at {r.peak_time} against service capacity {r.service_capacity:.0f}.")
    else:
        parts.append("No stop exceeds the configured risk thresholds in this window.")
    if moves:
        parts.append("Suggested moves: " + "; ".join(f"{m.buses} bus(es) {m.from_stop} to {m.to_stop} ({m.travel_min:.0f} min)" for m in moves[:3])
                     + f". Estimated unserved demand falls from {s['unserved_before']:.0f} to {s['unserved_after']:.0f}. These are advisory and need dispatcher approval.")
    else:
        parts.append("The optimiser found no feasible bus moves for the target slot.")
    return DEMO_PREFIX + " ".join(parts)


def build(svc: Services, req: BriefingRequest, provider: LLMProvider | None = None) -> BriefingResponse:
    svc.model.require()
    fc, rec, risks, moves = _facts(svc, req)
    s = rec["summary"]
    common = dict(headline=_headline(risks), top_risks=risks, moves=moves, unserved_before=s["unserved_before"],
                  unserved_after=s["unserved_after"], disclaimer=DISCLAIMER)
    provider = provider if provider is not None else build_provider(svc.settings)
    reason = None
    if provider is None:
        if svc.settings.llm_provider not in ("none", ""):
            reason = "no API key configured"
    else:
        facts_json = to_json(dict(forecast=dict(stops=fc["stops"][:6], totals=fc["totals"]), recommendations=rec))
        try:
            turn = provider.complete(SYSTEM, [{"role": "user", "content": f"FACTS (JSON):\n{facts_json}\n\nWrite the briefing."}], [])
            text = turn.text.strip()
            if not text:
                raise RuntimeError("empty LLM response")
            bad = ungrounded_numbers(text, [facts_json])
            warnings = [f"Numbers not found in backend facts (verify): {bad[:8]}"] if bad else []
            return BriefingResponse(narrative=text, mode="live_llm", provider=provider.name, model=provider.model, warnings=warnings, **common)
        except Exception as exc:  # timeouts, auth, rate limits
            log.warning("briefing LLM call failed: %s", exc)
            reason = f"{type(exc).__name__} while calling the LLM provider"
    return BriefingResponse(narrative=_template(risks, moves, rec), mode="demo", provider=None, model=None, fallback_reason=reason, **common)
