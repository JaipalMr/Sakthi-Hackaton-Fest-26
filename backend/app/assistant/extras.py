from backend.app.pipeline import Services, predict
from backend.app.schemas import (Announcement, AnnouncementRequest, AnnouncementResponse, ChaosRequest, ChaosResponse, ForecastContext)

log = logging.getLogger("extras")
RISK_RANK = {"low": 0, "elevated": 1, "high": 2}

# ------------------------------------------------------------------ Chaos Lab narration
CHAOS_SYSTEM = """You are a transport resilience analyst writing a red-team debrief for a festival control room.
STRICT RULES: use ONLY numbers, scenarios and stop names from the FACTS block; never invent figures. 4-5 plain-text sentences, under 130 words,
no markdown. Open with the score and grade, name the worst scenario and the weakest single stop, give the top 1-2 hardening actions,
and end by noting the data is synthetic and the score is a heuristic."""


def _chaos_template(r: ChaosResponse) -> str:
    return ("[DEMO MODE - template debrief, not generated by an LLM] " +
            f"Resilience score {r.score}/100 (grade {r.grade}). Worst scenario: {r.worst_case.label}, leaving up to {r.worst_case.extra_unserved:.0f} extra passengers unserved around {r.worst_case.worst_time}. "
            f"Weakest single stop: {r.weakest_link.label.replace(' closed', '')} ({r.weakest_link.extra_unserved:.0f} extra unserved if closed). "
            + r.hardening_tips[0] + " Hypothetical scenarios on synthetic data; the score is a heuristic.")


def chaos_report(svc: Services, req: ChaosRequest, provider: LLMProvider | None = None) -> ChaosResponse:
    c = req.context
    base = chaos.run(svc, ForecastContext(festival_id=c.festival_id, forecast_origin=c.forecast_origin, horizon_steps=c.horizon_steps), c.target_step)
    provider = provider if provider is not None else build_provider(svc.settings)
    reason = None
    if provider is None:
        if svc.settings.llm_provider not in ("none", ""):
            reason = "no API key configured"
    else:
        top = sorted(base.results, key=lambda x: -x.harm)[:5]
        facts = to_json(dict(score=base.score, grade=base.grade, slots_tested=base.slots_tested, worst_case=base.worst_case.model_dump(),
                             weakest_link=base.weakest_link.model_dump(), top_scenarios=[t.model_dump() for t in top], hardening_tips=base.hardening_tips))
        try:
            text = provider.complete(CHAOS_SYSTEM, [{"role": "user", "content": f"FACTS (JSON):\n{facts}\n\nWrite the debrief."}], []).text.strip()
            if not text:
                raise RuntimeError("empty LLM response")
            bad = ungrounded_numbers(text, [facts])
            return base.model_copy(update=dict(narrative=text, mode="live_llm", provider=provider.name, model=provider.model,
                                               warnings=[f"Numbers not found in backend facts (verify): {bad[:8]}"] if bad else []))
        except Exception as exc:
            log.warning("chaos narration failed: %s", exc)
            reason = f"{type(exc).__name__} while calling the LLM provider"
    return base.model_copy(update=dict(narrative=_chaos_template(base), mode="demo", fallback_reason=reason))


