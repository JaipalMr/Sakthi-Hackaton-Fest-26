def _template(lang: str, stop: str | None, alt: str | None, wait: int | None) -> str:
    t = T[lang]
    if not stop:
        return t["ok"]
    mid = t["both"] if alt and wait else t["alt"] if alt else t["wait"] if wait else ""
    return " ".join(x for x in (t["head"], mid, t["tail"]) if x).format(stop=stop, alt=alt, m=wait)


def _situation(svc: Services, ctx) -> tuple[str, str | None, str | None, int | None]:
    r = predict(svc, ForecastContext(festival_id=ctx.festival_id, forecast_origin=ctx.forecast_origin, horizon_steps=ctx.horizon_steps), ctx.scenario)
    ranked = sorted(r.forecasts, key=lambda f: (-RISK_RANK[f.peak_risk_level], -f.steps[f.peak_step - 1].load_ratio))
    worst = ranked[0]
    if worst.peak_risk_level != "high":
        return ("elevated" if worst.peak_risk_level == "elevated" else "calm"), None, None, None
    ps = worst.peak_step
    wait = next(((s.step - ps) * 15 for s in worst.steps if s.step > ps and s.risk_level == "low"), None)
    cands = [f for f in r.forecasts if f.stop_id != worst.stop_id and f.steps[ps - 1].risk_level == "low" and not f.steps[ps - 1].route_closed]
    alt = min(cands, key=lambda f: f.steps[ps - 1].load_ratio).stop_name if cands else None
    return "high", worst.stop_name, alt, wait


ANN_SYSTEM = """You write short passenger-information announcements for a festival bus network, in several languages.
STRICT RULES: use only the facts given (crowded stop, alternative stop, wait minutes). Keep stop names exactly as given (Latin script).
Calm, polite, at most 3 short sentences per language. The only digits allowed are the wait minutes (if given). No emojis, no markdown.
Output EXACTLY one line per requested language, formatted as  code|announcement text  (codes: en, hi, ta, es). Nothing else."""


def announcements(svc: Services, req: AnnouncementRequest, provider: LLMProvider | None = None) -> AnnouncementResponse:
    svc.model.require()
    c = req.context
    sit, stop, alt, wait = _situation(svc, c)
    langs = list(dict.fromkeys(req.languages))
    texts = {l: (_template(l, stop, alt, wait), "template") for l in langs}
    provider = provider if provider is not None else build_provider(svc.settings)
    reason, mode, pname, pmodel = None, "demo", None, None
    if provider is None:
        if svc.settings.llm_provider not in ("none", ""):
            reason = "no API key configured"
    else:
        facts = to_json(dict(situation=sit, crowded_stop=stop, alternative_stop=alt, wait_minutes=wait, languages=langs))
        try:
            out = provider.complete(ANN_SYSTEM, [{"role": "user", "content": f"FACTS (JSON):\n{facts}\n\nWrite the announcements."}], []).text
            for line in out.splitlines():
                code, _, body = line.partition("|")
                code, body = code.strip().lower(), body.strip()
                digits = set(re.findall(r"\d+", body))
                if code in texts and body and len(body) < 700 and digits <= ({str(wait)} if wait else set()) and (not stop or stop in body):
                    texts[code] = (body, "llm")
            if any(src == "llm" for _, src in texts.values()):
                mode, pname, pmodel = "live_llm", provider.name, provider.model
            else:
                reason = "LLM output could not be validated; templates used"
        except Exception as exc:
            log.warning("announcement LLM failed: %s", exc)
            reason = f"{type(exc).__name__} while calling the LLM provider"
    situation = {"high": f"{stop} is at high crowd risk", "elevated": "Elevated load somewhere, but no stop at high risk", "calm": "Network calm"}[sit]
    return AnnouncementResponse(
        situation=situation, crowded_stop=stop, alternative_stop=alt, wait_minutes=wait, mode=mode, provider=pname, model=pmodel, fallback_reason=reason,  # type: ignore[arg-type]
        announcements=[Announcement(lang=l, language=LANGS[l][0], speech_lang=LANGS[l][1], text=texts[l][0], source=texts[l][1]) for l in langs],  # type: ignore[arg-type]
        disclaimer="DRAFT machine-generated announcements about SYNTHETIC data. A bilingual staff member must review them before any real broadcast. " + DISCLAIMER.split(";")[0] + ".")
