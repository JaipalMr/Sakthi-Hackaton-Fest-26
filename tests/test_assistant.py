from backend.app.assistant import service as asvc
from backend.app.assistant.llm_provider import LLMTurn, ToolUse
from backend.app.assistant.tools import run_tool
from backend.app.config import OpsConfig, Settings
from backend.app.pipeline import Services
from backend.app.schemas import AssistantContext, AssistantRequest
from tests.conftest import FEST, ORIGIN

CTX = AssistantContext(festival_id=FEST, forecast_origin=ORIGIN, horizon_steps=8, target_step=3)


def req(msg):
    return AssistantRequest(message=msg, context=CTX)


class Scripted:
    name, model = "fake", "fake-model"

    def __init__(self, turns):
        self.turns, self.calls = list(turns), 0

    def complete(self, system, messages, tools):
        self.calls += 1
        t = self.turns.pop(0)
        if isinstance(t, Exception):
            raise t
        return t


def tu(name, args, id="t1"):
    return LLMTurn("", [ToolUse(id, name, args)], [{"type": "tool_use", "id": id, "name": name, "input": args}])


def test_demo_mode_without_key_is_labelled(svc):
    r = asvc.answer(svc, req("Which stops are at high risk?"))
    assert r.mode == "demo" and r.provider is None and r.model is None
    assert r.answer.startswith("[DEMO MODE") and "not generated by an LLM" in r.answer
    assert r.tool_calls and r.tool_calls[0].name == "get_demand_forecast" and r.tool_calls[0].ok


def test_demo_numbers_come_from_backend_tools(svc):
    r = asvc.answer(svc, req("Where should buses move?"))
    assert r.tool_calls[0].name == "get_deployment_recommendations"
    s = r.grounding["get_deployment_recommendations"]["summary"]
    assert f"{s['unserved_before']:.0f}" in r.answer


def test_demo_what_if_parses_parameters(svc):
    r = asvc.answer(svc, req("What if it rains 12 mm and the festival ends 30 minutes later?"))
    args = r.tool_calls[0].arguments
    assert r.tool_calls[0].name == "run_what_if_simulation"
    assert args["rainfall_mm_per_hr"] == 12.0 and args["festival_end_shift_min"] == 30
    assert "hypothetical" in r.answer or "simulation" in r.answer


def test_live_flow_uses_tools_then_answers(svc):
    p = Scripted([tu("get_demand_forecast", {"horizon_steps": 4}), LLMTurn("S01 is the busiest stop.")])
    r = asvc.answer(svc, req("Which stop is busiest?"), provider=p)
    assert r.mode == "live_llm" and r.provider == "fake" and r.tool_calls[0].ok and "get_demand_forecast" in r.grounding


def test_live_answer_without_tool_use_is_rejected(svc):
    r = asvc.answer(svc, req("Predict S01"), provider=Scripted([LLMTurn("It will be 500 people.")]))
    assert r.mode == "demo" and "ungrounded" in r.fallback_reason


def test_timeout_and_api_failure_fall_back_to_demo(svc):
    for exc in (TimeoutError("timed out"), RuntimeError("503 overloaded")):
        r = asvc.answer(svc, req("Which stops are at high risk?"), provider=Scripted([exc]))
        assert r.mode == "demo" and r.fallback_reason and r.answer.startswith("[DEMO MODE")


def test_invalid_tool_arguments_are_rejected_and_reported(svc):
    p = Scripted([tu("get_demand_forecast", {"horizon_steps": 99}), tu("get_stop_data", {"stop_ids": ["S99"]}, "t2"),
                  tu("hack_the_planet", {}, "t3"), LLMTurn("Could not run tools.")])
    r = asvc.answer(svc, req("x"), provider=p)
    assert [c.ok for c in r.tool_calls] == [False, False, False]
    assert r.mode == "live_llm"


def test_run_tool_validates_directly(svc):
    import pytest
    with pytest.raises(ValueError):
        run_tool(svc, "run_what_if_simulation", {"rainfall_mm_per_hr": -5}, CTX)
    with pytest.raises(ValueError):
        run_tool(svc, "get_demand_forecast", {"unexpected": 1}, CTX)


def test_ungrounded_number_detector():
    assert asvc.ungrounded_numbers("S01 peaks at 242 and 999", ['{"p": 242.4}']) == [999.0]


def test_tool_loop_round_limit(svc):
    s = Settings(llm_provider="anthropic", anthropic_api_key="x", llm_max_rounds=2, ops=OpsConfig())
    svc2 = Services(svc.store, svc.model, s)
    p = Scripted([tu("get_stop_data", {}), tu("get_stop_data", {}, "t2"), tu("get_stop_data", {}, "t3")])
    r = asvc.answer(svc2, req("loop"), provider=p)
    assert r.mode == "demo" and "maximum number of tool rounds" in r.fallback_reason


